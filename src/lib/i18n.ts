export const dictionaries: Record<Locale, Dict> = { ru, en, zh };

/**
 * Create a translation function for a given locale.
 *
 * Usage:
 *   const t = useTranslations(locale);
 *   t('settings.title')  → "Настройки" / "Settings" / "设置"
 */
export function createTranslator(locale: Locale): (key: string, params?: Record<string, string | number>) => string {
  const dict = dictionaries[locale];
  return (key: string, params?: Record<string, string | number>): string => {
    let value = dict[key];
    if (value === undefined) {
      // Fallback to Russian
      value = dictionaries.ru[key] ?? key;
    }
    if (typeof value === 'string' && params) {
      for (const [paramKey, paramValue] of Object.entries(params)) {
        value = value.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramValue));
      }
    }
    return typeof value === 'string' ? value : key;
  };
}

/**
 * Create a translator for a given language string (reads from store state).
 * Use this outside React components (e.g. in the store or API helpers).
 */
export function createTranslatorForLanguage(language: string): (key: string, params?: Record<string, string | number>) => string {
  const locale: Locale = SUPPORTED_LOCALES.includes(language as Locale) ? (language as Locale) : 'ru';
  return createTranslator(locale);
}
